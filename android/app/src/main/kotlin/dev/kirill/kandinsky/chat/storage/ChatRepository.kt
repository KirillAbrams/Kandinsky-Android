package dev.kirill.kandinsky.chat.storage
import dev.kirill.kandinsky.chat.domain.*
interface ChatRepository {
 /**
  * Определяет сохранение факта прочтения выбранного чата в местном хранилище
  * Вызывающая сторона ждёт завершения записи, а последующая сетевая доставка зависит от подключённого журнала изменений
  */
 fun markRead(chatID:ChatID,callback:(Result<Unit>)->Unit):Cancellation
 /**
  * Определяет чтение сохранённых сводок чатов с необязательным поисковым текстом
  * Возвращает данные для списка без необходимости загружать полные сообщения каждого чата
  */
 fun chats(matching:String,callback:(Result<List<ChatSummary>>)->Unit):Cancellation
 /**
  * Определяет чтение ограниченной страницы сообщений выбранного чата по направлению и опорному порядку
  * Вместе со строками возвращает границы страницы, необходимые для продолжения чтения более ранней или поздней истории
  */
 fun history(request:PageRequest,callback:(Result<HistoryPage>)->Unit):Cancellation
 /**
  * Определяет чтение компактного списка порядка, версий и предполагаемых высот строк выбранного чата
  * Сцена использует эти сведения для прокрутки всей истории без удержания полных сообщений и вложений
  */
 fun index(chatID:ChatID,callback:(Result<List<IndexedRow>>)->Unit):Cancellation
 /**
  * Определяет сохранение сообщения по постоянному номеру пользовательской операции
  * Возвращаемое изменение содержит данные для немедленного обновления чата после записи, независимо от последующего сетевого подтверждения
  */
 fun send(command:SendCommand,callback:(Result<MessageDelta>)->Unit):Cancellation
 /**
  * Определяет местное удаление сообщения по его постоянному номеру
  * Результат описывает удалённые строки и обновлённую сводку чата для согласованного изменения экрана
  */
 fun delete(messageID:MessageID,callback:(Result<MessageDelta>)->Unit):Cancellation
 /**
  * Определяет поиск номеров сохранённых сообщений по тексту внутри одного чата
  * Необязательная граница порядка позволяет продолжить поиск раньше найденного участка истории
  */
 fun search(chatID:ChatID,text:String,before:OrderKey?,callback:(Result<List<MessageID>>)->Unit):Cancellation
 /**
  * Определяет сохранение текста, вложений и состояния незавершённой отправки выбранного чата
  * Версия черновика нужна хранилищу для защиты нового ввода от запоздалой записи прежнего состояния
  */
 fun saveDraft(chatID:ChatID,draft:Draft,callback:(Result<Unit>)->Unit):Cancellation
 /**
  * Определяет восстановление местного черновика выбранного чата
  * Возвращаемые данные позволяют продолжить ввод и известную незавершённую отправку после закрытия экрана
  */
 fun draft(chatID:ChatID,callback:(Result<Draft>)->Unit):Cancellation
 /**
  * Определяет сохранение отдельной опоры чтения для выбранного чата
  * Опора хранит сообщение, положение внутри строки и связь с концом истории, чтобы возвращение не сбрасывало прокрутку
  */
 fun savePosition(chatID:ChatID,anchor:ReadingAnchor,callback:(Result<Unit>)->Unit):Cancellation
 /**
  * Определяет чтение ранее сохранённой опоры прокрутки одного чата
  * Отсутствие результата означает, что сохранённого места ещё нет и начальное положение выбирает открывающий экран
  */
 fun position(chatID:ChatID,callback:(Result<ReadingAnchor?>)->Unit):Cancellation
}
